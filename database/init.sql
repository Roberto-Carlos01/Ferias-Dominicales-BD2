-- =========================================================
-- SCRIPT DE INICIALIZACIÓN - Ferias Dominicales
-- Grupo #8 - Base de Datos 2
-- Incluye: Creación de tablas + tabla USUARIO + datos iniciales
-- =========================================================

CREATE DATABASE IF NOT EXISTS bdferias CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE bdferias;

-- =========================================================
-- ORDEN DE CREACIÓN:
-- UBICACION, FERIA, STAND, EXPOSITOR, INSTITUCION, PRODUCTO,
-- EXPOSICION, CONFORMAN, OFRECE, ORGANIZA, PATROCINA, USUARIO
-- =========================================================

CREATE TABLE IF NOT EXISTS UBICACION (
    IDUBICACION INT,
    NOMBRE VARCHAR(100),
    CIUDAD VARCHAR(100),
    ZONA VARCHAR(100),
    CAPACIDAD INT,
    REFERENCIA VARCHAR(200),
    PRIMARY KEY (IDUBICACION)
);

CREATE TABLE IF NOT EXISTS FERIA (
    IDFERIA INT,
    NOMBRE VARCHAR(100),
    DESCRIPCION VARCHAR(255),
    FECHA_INI DATE,
    FECHA_FIN DATE,
    HORA_INICIO VARCHAR(8),
    HORA_FIN VARCHAR(8),
    ESTADO VARCHAR(50),
    TIPO VARCHAR(50),
    IDUBICACION INT,
    PRIMARY KEY (IDFERIA),
    CONSTRAINT FK_FERIA_UBICACION FOREIGN KEY (IDUBICACION)
        REFERENCES UBICACION (IDUBICACION)
);

CREATE TABLE IF NOT EXISTS STAND (
    NROSTAND INT,
    IDFERIA INT,
    ANCHO DECIMAL(8,2),
    LARGO DECIMAL(8,2),
    UBICACIONINTERNA VARCHAR(100),
    ESTADO VARCHAR(50),
    CONSTRAINT PK_STAND PRIMARY KEY (NROSTAND, IDFERIA),
    CONSTRAINT FK_STAND_FERIA FOREIGN KEY (IDFERIA)
        REFERENCES FERIA (IDFERIA)
);

CREATE TABLE IF NOT EXISTS EXPOSITOR (
    CIEXPOSITOR VARCHAR(20),
    NOMBRE VARCHAR(50),
    PATERNO VARCHAR(50),
    MATERNO VARCHAR(50),
    CORREO VARCHAR(100),
    TELEFONO VARCHAR(20),
    PRIMARY KEY (CIEXPOSITOR)
);

CREATE TABLE IF NOT EXISTS INSTITUCION (
    NIT VARCHAR(30),
    RAZONSOCIAL VARCHAR(100),
    CORREO VARCHAR(100),
    TELEFONO VARCHAR(20),
    PRIMARY KEY (NIT)
);

CREATE TABLE IF NOT EXISTS PRODUCTO (
    IDPRODUCTO INT,
    NOMBREPROD VARCHAR(100),
    PRECIO DECIMAL(10,2),
    CATEGORIA VARCHAR(50),
    DESCRIPCIONPROD VARCHAR(255),
    PRIMARY KEY (IDPRODUCTO)
);

CREATE TABLE IF NOT EXISTS EXPOSICION (
    IDEXPOSICION INT,
    TITULOEXPOSICION VARCHAR(100),
    DESCRIPCION VARCHAR(255),
    IDFERIA INT,
    NROSTAND INT,
    PRIMARY KEY (IDEXPOSICION),
    CONSTRAINT UK_EXPOSICION_STAND UNIQUE (NROSTAND, IDFERIA),
    CONSTRAINT FK_EXPOSICION_STAND FOREIGN KEY (NROSTAND, IDFERIA)
        REFERENCES STAND (NROSTAND, IDFERIA)
);

CREATE TABLE IF NOT EXISTS CONFORMAN (
    CIEXPOSITOR VARCHAR(20),
    NROSTAND INT,
    IDFERIA INT,
    CARGO VARCHAR(50),
    CONSTRAINT PK_CONFORMAN PRIMARY KEY (CIEXPOSITOR, NROSTAND, IDFERIA),
    CONSTRAINT FK_CONFORMAN_EXPOSITOR FOREIGN KEY (CIEXPOSITOR)
        REFERENCES EXPOSITOR (CIEXPOSITOR),
    CONSTRAINT FK_CONFORMAN_STAND FOREIGN KEY (NROSTAND, IDFERIA)
        REFERENCES STAND (NROSTAND, IDFERIA)
);

CREATE TABLE IF NOT EXISTS OFRECE (
    IDFERIA INT,
    NROSTAND INT,
    IDPRODUCTO INT,
    UNIDADMEDIDA VARCHAR(30),
    STOCK INT,
    CONSTRAINT PK_OFRECE PRIMARY KEY (IDFERIA, NROSTAND, IDPRODUCTO),
    CONSTRAINT FK_OFRECE_STAND FOREIGN KEY (NROSTAND, IDFERIA)
        REFERENCES STAND (NROSTAND, IDFERIA),
    CONSTRAINT FK_OFRECE_PRODUCTO FOREIGN KEY (IDPRODUCTO)
        REFERENCES PRODUCTO (IDPRODUCTO)
);

CREATE TABLE IF NOT EXISTS ORGANIZA (
    IDFERIA INT,
    NIT VARCHAR(30),
    ROL VARCHAR(50),
    CONSTRAINT PK_ORGANIZA PRIMARY KEY (IDFERIA, NIT),
    CONSTRAINT FK_ORGANIZA_FERIA FOREIGN KEY (IDFERIA)
        REFERENCES FERIA (IDFERIA),
    CONSTRAINT FK_ORGANIZA_INSTITUCION FOREIGN KEY (NIT)
        REFERENCES INSTITUCION (NIT)
);

CREATE TABLE IF NOT EXISTS PATROCINA (
    IDFERIA INT,
    NIT VARCHAR(30),
    TIPO_APOYO VARCHAR(50),
    CANTIDAD DECIMAL(10,2),
    DETALLES VARCHAR(200),
    CONSTRAINT PK_PATROCINA PRIMARY KEY (IDFERIA, NIT),
    CONSTRAINT FK_PATROCINA_FERIA FOREIGN KEY (IDFERIA)
        REFERENCES FERIA (IDFERIA),
    CONSTRAINT FK_PATROCINA_INSTITUCION FOREIGN KEY (NIT)
        REFERENCES INSTITUCION (NIT)
);

-- =========================================================
-- TABLA USUARIO (Extensión para autenticación)
-- ciExpositor es FK opcional que vincula usuario con EXPOSITOR
-- =========================================================
CREATE TABLE IF NOT EXISTS USUARIO (
    IDUSUARIO INT AUTO_INCREMENT PRIMARY KEY,
    CORREO VARCHAR(150) NOT NULL UNIQUE,
    PASSWORDHASH VARCHAR(255) NOT NULL,
    ROL ENUM('ADMIN', 'USUARIO') NOT NULL DEFAULT 'USUARIO',
    ESTADO ENUM('ACTIVO', 'INACTIVO') NOT NULL DEFAULT 'ACTIVO',
    CIEXPOSITOR VARCHAR(20) NULL,
    FECHACREACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FECHAACTUALIZACION DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT FK_USUARIO_EXPOSITOR FOREIGN KEY (CIEXPOSITOR)
        REFERENCES EXPOSITOR (CIEXPOSITOR)
);
